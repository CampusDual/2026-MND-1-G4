CREATE TABLE distributor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    active BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE store (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distributor_id BIGINT NOT NULL,
    name VARCHAR(120) NOT NULL,
    active BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT uq_store_distributor_name UNIQUE (distributor_id, name),
    CONSTRAINT uq_store_id_distributor UNIQUE (id, distributor_id),
    CONSTRAINT fk_store_distributor FOREIGN KEY (distributor_id) REFERENCES distributor (id)
);

CREATE TABLE waiter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distributor_id BIGINT NOT NULL,
    store_id BIGINT NOT NULL,
    name VARCHAR(120) NOT NULL,
    active BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT uq_waiter_store_name UNIQUE (store_id, name),
    CONSTRAINT fk_waiter_store_distributor FOREIGN KEY (store_id, distributor_id)
        REFERENCES store (id, distributor_id)
);

CREATE TABLE manager_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distributor_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL UNIQUE,
    CONSTRAINT fk_manager_profile_distributor FOREIGN KEY (distributor_id) REFERENCES distributor (id),
    CONSTRAINT fk_manager_profile_user FOREIGN KEY (user_id) REFERENCES users (id)
);
